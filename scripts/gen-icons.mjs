// Write the icons both apps use, from Lucide (ISC license), as small checked-in files:
//   web/src/lib/icons.ts     for the web app (the <Icon> component reads it)
//   desktop/ui/icons.js      for the desktop app (icon("name") returns an <svg> string)
//
//   cd web && pnpm install && node ../scripts/gen-icons.mjs
//
// To add an icon, add its Lucide name below (https://lucide.dev/icons) and run this again.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'web', 'node_modules', 'lucide-static', 'icons');

const NAMES = [
  // places
  'folder', 'folder-open', 'folder-kanban', 'puzzle', 'briefcase', 'clapperboard', 'star', 'folders', 'folder-input', 'folder-sync', 'hard-drive', 'server', 'building-2', 'layers',
  // people and accounts
  'user-round', 'users', 'user-plus', 'key-round', 'log-in', 'log-out', 'shield', 'shield-check', 'shield-check', 'mail', 'mail-plus', 'settings', 'palette',
  // moving files
  'cloud-download', 'cloud-upload', 'download', 'upload', 'send', 'refresh-cw', 'loader-circle', 'external-link', 'link', 'copy',
  // history and branches
  'history', 'clock', 'calendar-clock', 'git-branch', 'git-merge', 'git-pull-request-arrow', 'rotate-ccw', 'undo-2', 'bookmark', 'bookmark-plus', 'save',
  // files and kinds
  'file', 'files', 'file-text', 'file-image', 'file-audio', 'file-video', 'file-code', 'file-box', 'file-archive', 'file-clock', 'file-pen',
  'image', 'box', 'music', 'film', 'archive',
  // states and actions
  'pencil', 'pencil-line', 'plus', 'minus', 'lock', 'lock-open', 'hand', 'bell', 'trash-2', 'x', 'check', 'check-check', 'circle-check',
  'circle-alert', 'triangle-alert', 'info', 'search', 'tag', 'tags', 'eye', 'sparkles', 'wrench', 'scroll-text', 'layout-dashboard',
  // navigation
  'arrow-left', 'arrow-right', 'chevron-right', 'chevron-down', 'ellipsis', 'sun', 'moon', 'monitor',
];

const icons = {};
for (const n of NAMES) {
  const svg = fs.readFileSync(path.join(SRC, `${n}.svg`), 'utf8');
  const inner = svg.replace(/<!--[\s\S]*?-->/g, '').replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>[\s\S]*$/, '').replace(/\s*\n\s*/g, '').trim();
  icons[n] = inner;
}
const version = JSON.parse(fs.readFileSync(path.join(SRC, '..', 'package.json'), 'utf8')).version;
const head = `Icons from Lucide ${version} (https://lucide.dev), ISC License.\nCopyright (c) for portions of Lucide are held by Cole Bemis 2013-2022 as part of Feather (MIT).\nAll other copyright (c) for Lucide are held by Lucide Contributors 2022.\nGenerated by scripts/gen-icons.mjs; do not edit by hand.`;
const body = JSON.stringify(icons, null, 1);

fs.writeFileSync(path.join(ROOT, 'web', 'src', 'lib', 'icons.ts'),
  `${head.split('\n').map((l) => `// ${l}`).join('\n')}\n\nexport const ICONS = ${body} as const;\n\nexport type IconName = keyof typeof ICONS;\n`);

fs.writeFileSync(path.join(ROOT, 'desktop', 'ui', 'icons.js'),
  `${head.split('\n').map((l) => `// ${l}`).join('\n')}\n"use strict";\n\nconst ICONS = ${body};\n\n` +
  `/** An icon as an <svg> string: drawn in the text colour, sized by CSS (.ic, 1em by default). */\n` +
  `function icon(name, cls = "") {\n  const inner = ICONS[name];\n  if (!inner) return "";\n` +
  `  return \`<svg class="ic \${cls}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">\${inner}</svg>\`;\n}\n`);
// The web app also draws icons in CSS: an element with data-ic="name" gets the icon before its
// text, filled with the text colour (a mask), so React never has to know about it.
const uri = (inner) => `url("data:image/svg+xml,${encodeURIComponent(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="black" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${inner}</svg>`)}")`;
fs.writeFileSync(path.join(ROOT, 'web', 'src', 'styles', 'icons.css'),
  `${head.split('\n').map((l) => `/* ${l} */`).join('\n')}\n` +
  `[data-ic]::before { content: ""; display: inline-block; flex: none; width: 1.1em; height: 1.1em; margin-right: .45em; vertical-align: -.2em; background: currentColor; -webkit-mask: var(--ic) center / contain no-repeat; mask: var(--ic) center / contain no-repeat; }\n` +
  NAMES.map((n) => `[data-ic="${n}"] { --ic: ${uri(icons[n])}; }`).join('\n') + '\n');
console.log(`${NAMES.length} icons written`);
