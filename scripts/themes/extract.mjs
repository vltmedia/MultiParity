// Pull the chosen themes out of the theme gallery (design/themes/index.html) into the shared
// file both apps read (desktop/ui/themes.json). Run after changing the gallery:
//
//   node scripts/themes/extract.mjs
//
// The list of themes to ship is CHOSEN below (Ember first: it is the default).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const CHOSEN = [
  "ember",
  "aqua", "graphite", "midnight", "riso", "terminal", "neon", "hud", "icelab", "mainframe", "cyberdeck",
  "acid", "bubblegum", "y2k", "mono", "deepocean", "palenight", "repodark", "dracula",
  "frosted", "liquid", "spatial", "acrylic", "auroraglass", "neonglass", "oceanglass", "rosequartz",
  "aero", "aeroeco", "aerobubbles", "vista",
  "pocket", "bevel", "onebit", "vapor", "notebook", "sticky", "bauhaus", "memphis", "arcade",
  "mission", "hazard", "kawaii", "biolum", "flowers", "lofi", "tabloid",
];

const html = readFileSync(join(root, "design/themes/index.html"), "utf8");
const start = html.indexOf("const T = [");
const end = html.indexOf("];", html.indexOf("// ---- Novelty")) + 1;
if (start < 0 || end <= 0) throw new Error("could not find the theme list in the gallery");
const T = new Function(`${html.slice(start, end)}; return T;`)();
const byId = new Map(T.map((t) => [t.id, t]));
const out = CHOSEN.map((id) => {
  const t = byId.get(id);
  if (!t) throw new Error(`no theme ${id} in the gallery`);
  const { current, ...rest } = t;
  return rest;
});
const file = join(root, "desktop/ui/themes.json");
writeFileSync(file, JSON.stringify(out, null, 1) + "\n");
// The desktop app reads the same list as a script, so the chosen theme applies before first paint.
writeFileSync(join(root, "desktop/ui/themes.js"), "// Generated by scripts/themes/extract.mjs from design/themes. Do not edit.\nglobalThis.MP_THEMES = " + JSON.stringify(out) + ";\n");
console.log(`wrote ${out.length} themes to ${file} and themes.js`);
